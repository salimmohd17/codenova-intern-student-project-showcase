CREATE TABLE IF NOT EXISTS project_ratings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  rater_id TEXT NOT NULL,
  rating INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT project_ratings_rating_check CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT project_ratings_project_rater_unique UNIQUE (project_id, rater_id)
);

CREATE INDEX IF NOT EXISTS project_ratings_project_id_idx
  ON project_ratings (project_id);
